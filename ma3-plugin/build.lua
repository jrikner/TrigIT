-- Bundles src/*.lua and adapter/TrigIT.lua into the plugin MA3 imports:
-- dist/TrigIT.xml and dist/TrigIT.lua. One Lua file, because an MA3 plugin
-- has no require path. Run from ma3-plugin: `lua build.lua`, or
-- `lua build.lua --check` to fail if dist/ is out of date (CI does).

local MODULES = { "json", "commands", "trigit_plan", "ma3", "timecode", "engine", "live" }
local VERSION = "0.1.0"

local function read(path)
    local file = assert(io.open(path, "rb"))
    local text = file:read("a")
    file:close()
    return text
end

local parts = {
    "-- SPDX-License-Identifier: GPL-3.0-or-later",
    "-- TrigIT " .. VERSION .. " for grandMA3. Generated by ma3-plugin/build.lua from src/ and",
    "-- adapter/: edit those, not this file. https://github.com/jrikner/TrigIT",
    "",
    "local modules, loaded = {}, {}",
    "local function require(name)",
    "    if loaded[name] == nil then loaded[name] = modules[name]() end",
    "    return loaded[name]",
    "end",
}
for _, name in ipairs(MODULES) do
    parts[#parts + 1] = ("\nmodules[%q] = function()\n%s\nend"):format(name, read("src/" .. name .. ".lua"))
end
parts[#parts + 1] = "\n" .. read("adapter/TrigIT.lua")
local files = {
    ["dist/TrigIT.lua"] = table.concat(parts, "\n"),
    ["dist/TrigIT.xml"] = ([[
<?xml version="1.0" encoding="UTF-8"?>
<GMA3 DataVersion="2.5.1.0">
  <Plugin Name="TrigIT" Author="TrigIT" Version="%s">
    <ComponentLua Name="TrigIT" FileName="TrigIT.lua" />
  </Plugin>
</GMA3>
]]):format(VERSION),
}

local check = arg[1] == "--check"
for path, text in pairs(files) do
    if check then
        local ok, current = pcall(read, path)
        if not ok or current ~= text then
            io.stderr:write(path .. " is out of date: run `lua build.lua` in ma3-plugin and commit dist/\n")
            os.exit(1)
        end
    else
        local file = assert(io.open(path, "wb"))
        file:write(text)
        file:close()
    end
end
print(check and "dist/ is up to date" or "wrote dist/TrigIT.xml and dist/TrigIT.lua")
